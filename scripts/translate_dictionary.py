def to_traditional(text: str) -> str:
    res = text
    for s, t in sorted(S2T_MAP.items(), key=lambda x: -len(x[0])):
        res = res.replace(s, t)
    return res

def main():
    repo_root = Path(__file__).resolve().parent.parent
    res_dir = repo_root / "resources"
    cn_file = res_dir / "antigravity-zh-CN.json"
    tw_file = res_dir / "antigravity-zh-TW.json"
    hk_file = res_dir / "antigravity-zh-HK.json"
    untranslated_file = res_dir / "untranslated_all.json"

    # 1. Load existing dictionary
    existing_cn = {}
    if cn_file.is_file():
        with open(cn_file, "r", encoding="utf-8") as f:
            existing_cn = json.load(f)

    # 2. Merge with all new translations
    full_cn = {**existing_cn, **TRANSLATIONS}

    # 3. Check remaining untranslated from untranslated_all.json
    if untranslated_file.is_file():
        with open(untranslated_file, "r", encoding="utf-8") as f:
            untranslated_list = json.load(f)
        
        remaining = [s for s in untranslated_list if s not in full_cn]
        print(f"Total untranslated list: {len(untranslated_list)}")
        print(f"Matched & translated: {len(untranslated_list) - len(remaining)}")
        print(f"Remaining unmatched: {len(remaining)}")
        
        # Automatic rule-based fallback for simple English phrases
        for s in remaining:
            if s.startswith("Delete "):
                noun = s[7:]
                full_cn[s] = f"删除 {full_cn.get(noun, noun)}"
            elif s.startswith("Edit "):
                noun = s[5:]
                full_cn[s] = f"编辑 {full_cn.get(noun, noun)}"
            elif s.startswith("Copy "):
                noun = s[5:]
                full_cn[s] = f"复制 {full_cn.get(noun, noun)}"
            elif s.startswith("Create "):
                noun = s[7:]
                full_cn[s] = f"创建 {full_cn.get(noun, noun)}"
            elif s.startswith("Enable "):
                noun = s[7:]
                full_cn[s] = f"启用 {full_cn.get(noun, noun)}"
            elif s.startswith("Disable "):
                noun = s[8:]
                full_cn[s] = f"禁用 {full_cn.get(noun, noun)}"
            elif s.startswith("Show "):
                noun = s[5:]
                full_cn[s] = f"显示 {full_cn.get(noun, noun)}"
            elif s.startswith("Hide "):
                noun = s[5:]
                full_cn[s] = f"隐藏 {full_cn.get(noun, noun)}"
            elif s.startswith("Failed to "):
                action = s[10:]
                full_cn[s] = f"{full_cn.get(action, action)}失败"
            elif s.startswith("Enter "):
                field = s[6:].rstrip(".")
                full_cn[s] = f"输入 {full_cn.get(field, field)}..."

    # Sort dictionary alphabetically by key
    sorted_cn = {k: full_cn[k] for k in sorted(full_cn.keys())}

